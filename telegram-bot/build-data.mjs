// Extracts the store list from the app's single source of truth (../stores.json,
// fetched at runtime by index.html) and writes a slim, bot-only module
// (stores.gen.js). This keeps ONE canonical dataset instead of a second
// hand-maintained copy, and it does NOT create a public raw-JSON endpoint: the
// output is bundled into the Worker at deploy time and git-ignored. Only the
// fields the bot needs are kept.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const jsonPath = fileURLToPath(new URL('../stores.json', import.meta.url));
const outPath = fileURLToPath(new URL('./stores.gen.js', import.meta.url));

const STORES = JSON.parse(readFileSync(jsonPath, 'utf8'));
if (!Array.isArray(STORES) || !STORES.length) throw new Error('stores.json did not parse to a non-empty array');

// Drop the watermark canary and keep only what the bot renders / reasons about.
const slim = STORES
  .filter((s) => !s.watermark)
  .map((s) => ({
    id: s.id,
    name: s.name,
    address: s.addressEn || s.address || '',
    pricing: s.pricing || 'item',
    restockDay: s.restockDay || null, // 'mon'..'fri' fallback — only meaningful on a 7-day cycle
    restockDate: s.restock_date || null, // concrete last-delivery date — works for any cycle length
    restockDates: Array.isArray(s.restockDates) && s.restockDates.length ? s.restockDates : null, // chain's published calendar; beats both fields above
    cycle: s.cycle || 7, // days per restock cycle, for cycle-aware duplicate-visit detection
    dailyDrop: s.dailyDrop || undefined, // restocks every day — no cycle to predict, so restock alerts decline politely
    lat: s.lat,
    lng: s.lng,
    promo: s.promo || null, // optional paid promotion { tier, offer, until } — drives the sponsored slot
  }));

const banner = '// AUTO-GENERATED by build-data.mjs from ../stores.json — do not edit by hand.\n';
writeFileSync(outPath, banner + 'export const STORES = ' + JSON.stringify(slim) + ';\n');

const withSchedule = slim.filter((s) => s.restockDay).length;
const withDate = slim.filter((s) => s.restockDate).length;
console.log(`Generated stores.gen.js — ${slim.length} stores (${withSchedule} with a fixed weekly restock day, ${withDate} with a dated restock).`);
